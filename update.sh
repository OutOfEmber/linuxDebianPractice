#!/bin/bash

# Скрипт для автоматического обновления приложения через git pull

echo "==================================="
echo "Начинаю обновление приложения..."
echo "==================================="

# Переходим в директорию проекта
cd ~/tereshenko/linuxDebianPractice || {
    echo "Ошибка: Не удалось перейти в директорию проекта"
    exit 1
}

# Проверяем, есть ли изменения в репозитории
echo "Проверяю обновления в git репозитории..."

# Сохраняем текущий коммит
OLD_COMMIT=$(git rev-parse HEAD)

# Выполняем git pull
git pull origin main || git pull origin master || {
    echo "Ошибка: Не удалось выполнить git pull"
    exit 1
}

# Получаем новый коммит
NEW_COMMIT=$(git rev-parse HEAD)

# Проверяем, были ли изменения
if [ "$OLD_COMMIT" = "$NEW_COMMIT" ]; then
    echo "Нет новых изменений. Обновление не требуется."
else
    echo "Обнаружены изменения! Обновляю..."
    echo "Старый коммит: $OLD_COMMIT"
    echo "Новый коммит: $NEW_COMMIT"
    
    # Если сервер запущен через PM2, перезапускаем его
    if command -v pm2 &> /dev/null; then
        echo "Перезапускаю приложение через PM2..."
        pm2 restart test-api
        echo "Приложение перезапущено"
    else
        echo "PM2 не найден. Сервер нужно перезапустить вручную"
    fi
fi

echo "==================================="
echo "Обновление завершено!"
echo "==================================="
